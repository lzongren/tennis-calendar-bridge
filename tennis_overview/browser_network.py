"""DNS-pinned read relay; browser-generated catalog POSTs have a separate policy."""

from __future__ import annotations

import http.client
import socket
import ssl
from dataclasses import dataclass
from urllib.parse import urlsplit, urlunsplit

from .browser_protocol import AUTH_HOST, read_url
from .browser_query_policy import validate_catalog_query
from .public_web import public_addresses


@dataclass(frozen=True)
class Resource:
    status: int
    headers: dict[str, str]
    body: bytes


def get_resource(
    url: str, headers: dict[str, str], *, portal_session: bool, post_body: bytes | None = None
) -> Resource:
    """One hop only. Browser redirects re-enter the same policy and DNS checks."""
    parsed = urlsplit(read_url(url, document=False))
    host = parsed.hostname or ""
    if post_body is not None:
        validate_catalog_query(url, post_body)
    addresses = public_addresses(host, 443)
    conn = http.client.HTTPConnection(host, 443, timeout=8)
    sock = socket.create_connection((addresses[0], 443), timeout=8)
    try:
        conn.sock = ssl.create_default_context().wrap_socket(sock, server_hostname=host)
        forwarded = {
            "Host": host,
            "Accept-Encoding": "identity",
            # This request is made by our HTTP relay, not Chromium's TLS stack.
            "User-Agent": "TennisCalendarBridge/0.2 (+public-course-discovery)",
            "Accept": headers.get("accept", "*/*"),
        }
        if post_body is not None:
            forwarded["Content-Type"] = "application/json"
        # A dedicated profile may also accumulate third-party cookies during human
        # login. Do not send those, or any bearer/worker credential, to subresources.
        if portal_session and host == AUTH_HOST:
            for key in ("cookie", "referer", "origin"):
                if key in headers:
                    forwarded[key] = headers[key]
            # Preserve the rendered app's content negotiation. Dropping these
            # makes MVC return an HTML shell where its frontend expects JSON.
            for key in (
                "content-type",
                "x-requested-with",
                "x-requested-by",
                "reactsubmit",
                "uiculture",
            ):
                value = headers.get(key, "")
                if (
                    value
                    and len(value) <= 128
                    and value.isascii()
                    and not any(ord(char) < 32 or ord(char) == 127 for char in value)
                ):
                    forwarded[key] = value
            # Public catalog POSTs carry organization context generated by the
            # anonymous frontend. Keep it at its original origin, never in logs.
            context = headers.get("requestdata", "")
            if (
                post_body is not None
                and 0 < len(context) <= 2048
                and all(32 <= ord(char) < 127 for char in context)
            ):
                forwarded["requestdata"] = context
        conn.request(
            "POST" if post_body is not None else "GET",
            urlunsplit(("", "", parsed.path or "/", parsed.query, "")),
            body=post_body,
            headers=forwarded,
        )
        response = conn.getresponse()
        body = response.read(4_000_001)
        if len(body) > 4_000_000:
            raise ValueError("Browser resource exceeds size budget")
        allowed = {
            "content-type",
            "content-encoding",
            "location",
            "access-control-allow-origin",
            "access-control-allow-credentials",
            "content-security-policy",
            "x-content-type-options",
        }
        outgoing = {
            key.lower(): value for key, value in response.getheaders() if key.lower() in allowed
        }
        if portal_session and host == AUTH_HOST:
            cookies = response.headers.get_all("Set-Cookie", [])
            if cookies:
                outgoing["set-cookie"] = "\n".join(cookies)
        return Resource(response.status, outgoing, body)
    finally:
        conn.close()
        sock.close()
